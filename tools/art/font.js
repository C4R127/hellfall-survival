const CHARS = Object.keys(G).join('');
const GW = 5, GH = 7;

/** Hoja: celdas de 7×9 (glifo + 1 px de margen para el contorno). fill = blanco, shadow = contorno negro. */
function fontSheets() {
  const cw = GW + 2, ch = GH + 2;
  const fill = new Img(cw * CHARS.length, ch), shadow = new Img(cw * CHARS.length, ch);
  [...CHARS].forEach((c, i) => {
    const rows = G[c];
    rows.forEach((row, y) => [...row].forEach((p, x) => {
      if (p !== '#') return;
      fill.set(i * cw + 1 + x, 1 + y, '#ffffff');
      for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) shadow.set(i * cw + 1 + x + dx, 1 + y + dy, '#05040a');
    }));
  });
  return { fill, shadow, cw, ch };
}

/** Escribe texto en un Img (para señalización y logotipo). */
function drawText(img, text, x, y, color, scale = 1) {
  let cx = x;
  for (const c of text.toUpperCase()) {
    const rows = G[c] || G[' '];
    rows.forEach((row, yy) => [...row].forEach((p, xx) => {
      if (p === '#') img.rect(cx + xx * scale, y + yy * scale, scale, scale, color);
    }));
    cx += (GW + 1) * scale;
  }
  return cx - x;
}
function textWidth(text, scale = 1) { return text.length * (GW + 1) * scale - scale; }

module.exports = { G, CHARS, GW, GH, fontSheets, drawText, textWidth };
